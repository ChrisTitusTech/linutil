#!/bin/sh -e

. ../../common-script.sh

checkRepo() {
    repoName='cachyos(-(v[34]|core-v[34]|extra-v[34]|testing-v3|znver4|core-znver4|extra-znver4))?'
    if ! repoList=$(pacman-conf --repo-list); then
        printf '%s\n' "Could not read the pacman repository configuration." >&2
        return 1
    fi
    activeRepos=$(printf '%s\n' "$repoList" | grep -E "^$repoName\$" || :)
}

checkGrub() {
    if ! command_exists grub-mkconfig; then
        printf "%b\n" "${RED}Changing the default kernel requires GRUB. Other bootloaders, including Limine and systemd-boot, are not supported by this action.${RC}"
        return 1
    fi
    if ! rootFilesystem=$(findmnt -n -o FSTYPE --target /) || [ -z "$rootFilesystem" ] || [ "$rootFilesystem" = zfs ]; then
        printf '%s\n' "Verify and change the kernel default manually when the root filesystem is ZFS or cannot be identified." >&2
        return 1
    fi
    checkEscalationTool
    if ! "$ESCALATION_TOOL" test -x /etc/grub.d/10_linux; then
        printf '%s\n' "Enable the standard GRUB Linux menu generator before changing the kernel default." >&2
        return 1
    fi
    if ! "$ESCALATION_TOOL" test -r /etc/default/grub ||
        ! "$ESCALATION_TOOL" test -d /boot/grub ||
        ! "$ESCALATION_TOOL" test -x /boot/grub ||
        ! "$ESCALATION_TOOL" test -w /etc/default ||
        ! "$ESCALATION_TOOL" test -w /boot/grub; then
        printf '%s\n' "Changing the default kernel requires GRUB and writable /etc/default and /boot/grub directories." >&2
        return 1
    fi
    if "$ESCALATION_TOOL" test -L /etc/default/grub || "$ESCALATION_TOOL" test -L /boot/grub/grub.cfg; then
        printf '%s\n' "GRUB settings or config are managed through a symlink. Change the kernel default manually." >&2
        return 1
    fi
    if "$ESCALATION_TOOL" test -e /boot/grub/custom.cfg; then
        printf '%s\n' "GRUB loads /boot/grub/custom.cfg at boot. Verify and change the kernel default manually." >&2
        return 1
    fi
    if "$ESCALATION_TOOL" test -e /boot/grub/grub.cfg &&
        ! "$ESCALATION_TOOL" grep -Fq 'It is automatically generated by' /boot/grub/grub.cfg; then
        printf '%s\n' "The active grub.cfg does not appear to be generated. Change the kernel default manually." >&2
        return 1
    fi
    if ! "$ESCALATION_TOOL" grep -q '^GRUB_DEFAULT=' /etc/default/grub; then
        printf "%b\n" "${RED}No GRUB_DEFAULT setting found in /etc/default/grub.${RC}"
        return 1
    fi
    # shellcheck disable=SC2016
    if ! "$ESCALATION_TOOL" awk -v quote="'" '
        /^GRUB_DEFAULT=/ {
            count++
            if ($0 !~ /^GRUB_DEFAULT=("[^"]*"|[[:alnum:]_.\/>-]+)[[:space:]]*(#.*)?$/ &&
                $0 !~ ("^GRUB_DEFAULT=" quote "[^" quote "]*" quote "[[:space:]]*(#.*)?$"))
                invalid = 1
        }
        END { exit (count != 1 || invalid) }
    ' /etc/default/grub; then
        printf '%s\n' "GRUB_DEFAULT must be a single standalone assignment. Change the default manually." >&2
        return 1
    fi
    # shellcheck disable=SC2016
    if ! "$ESCALATION_TOOL" sh -c '
        for config in /etc/default/grub.d/*.cfg; do
            [ -f "$config" ] || continue
            if grep -Eq "^[[:space:]]*(export[[:space:]]+)?GRUB_DEFAULT[[:space:]]*=" "$config"; then
                exit 1
            fi
        done
    '; then
        printf '%s\n' "A GRUB drop-in overrides the default. Change the kernel default manually." >&2
        return 1
    fi
    printf '%s\n' "Continue only if this machine boots from /boot/grub/grub.cfg. Choose option 6 to skip kernel selection during removal."
    printf '%s' "Does this machine boot from that GRUB config? [y/N] "
    read -r grubConfirmed
    case "$grubConfirmed" in
        y|Y) ;;
        *) return 1 ;;
    esac
}

preflightGrub() (
    preflightConfig=$("$ESCALATION_TOOL" mktemp /boot/grub/grub.cfg.linutil.preflight.XXXXXX)
    trap '"$ESCALATION_TOOL" rm -f -- "$preflightConfig" "$preflightConfig.new"' 0
    "$ESCALATION_TOOL" grub-mkconfig -o "$preflightConfig"
)

runRepoHelper() (
    workdir=$(mktemp -d)
    trap 'rm -rf -- "$workdir" 2>/dev/null || "$ESCALATION_TOOL" rm -rf -- "$workdir"' 0
    cd "$workdir"
    curl -f https://mirror.cachyos.org/cachyos-repo.tar.xz -o cachyos-repo.tar.xz
    tar xvf cachyos-repo.tar.xz
    cd cachyos-repo
    if [ "${2:-}" = --reset-kernel ]; then
        updateGrubDefault linux
    fi
    "$ESCALATION_TOOL" ./cachyos-repo.sh "${1:---install}"
)

setupRepos() {
    checkRepo
    if [ -n "$activeRepos" ]; then
        printf "%b\n" "CachyOS repos already configured"
    elif grep -Eq "^[[:space:]]*#[[:space:]]*\[$repoName\][[:space:]]*(#.*)?\$" /etc/pacman.conf; then
        printf "%b\n" "Enable the commented CachyOS repos in /etc/pacman.conf before continuing."
        return 1
    else
        if ! LC_ALL=C /lib/ld-linux-x86-64.so.2 --help 2>/dev/null |
            grep -Fq 'x86-64-v3 (supported, searched)'; then
            printf '%s\n' "Installing CachyOS repos requires an x86-64-v3 compatible CPU and glibc loader." >&2
            return 1
        fi
        printf '%s\n' "The CachyOS installer adds a trusted signing key, replaces pacman, and upgrades system packages."
        printf '%s' "Continue with CachyOS installation? [y/N] "
        read -r confirm
        case "$confirm" in
            y|Y) ;;
            *) return 1 ;;
        esac
        printf "%b\n" "Installing CachyOS repo.."
        runRepoHelper
        checkRepo
        if [ -z "$activeRepos" ]; then
            printf "%b\n" "The installer did not enable CachyOS repos in /etc/pacman.conf."
            return 1
        fi
    fi
}

findGrubEntry() {
    # GRUB's 10_linux assigns stable IDs to its advanced kernel entries.
    # shellcheck disable=SC2016
    "$ESCALATION_TOOL" awk -F "'" -v kernel="$1" '
        /^### BEGIN .*[/]10_linux ###$/ { linux = 1 }
        /^### END .*[/]10_linux ###$/ { linux = 0 }
        !linux { next }
        /^}/ { submenu = "" }
        /^[[:space:]]*}/ { path = ""; image = "" }
        /\$menuentry_id_option / {
            split(substr($0, index($0, "$menuentry_id_option ") + length("$menuentry_id_option ")), fields, FS)
            id = fields[2]
            if (id !~ /^[[:alnum:]_\/-]+$/) next
            if ($1 ~ /^submenu[[:space:]]/) submenu = id
            if ($1 ~ /^[[:space:]]*menuentry[[:space:]]/) {
                path = ($1 ~ /^[[:space:]]/ && submenu != "" ? submenu ">" : "") id
                if (id ~ /-recovery-/ || id ~ /^gnulinux-simple-/) path = ""
            }
        }
        path != "" && $1 ~ /^[[:space:]]+linux(efi)?[[:space:]]/ {
            split($1, args, /[[:space:]]+/)
            image = (args[3] == "" ? $2 : args[3])
            sub(/^.*[/]/, "", image)
            sub(/^vmlinuz-/, "", image)
        }
        path != "" && image != "" && $1 ~ /^[[:space:]]+initrd(efi)?[[:space:]]/ {
            for (i = 1; i <= NF; i++) {
                count = split($i, args, /[[:space:]]+/)
                for (j = 1; j <= count; j++) {
                    sub(/^.*[/]/, "", args[j])
                    if (args[j] != "initramfs-" image ".img" &&
                        args[j] != "initramfs-" image "-fallback.img" &&
                        args[j] != "booster-" image ".img" &&
                        args[j] != "initrd-" image ".img" &&
                        args[j] != "initrd.img-" image) continue
                    if (image == kernel) {
                        print path
                        found = 1
                        exit
                    }
                    if (kernel == "linux" && image == "linux-lts" &&
                        (fallback == "" || args[j] == "initramfs-linux-lts.img")) fallback = path
                }
            }
        }
        END {
            if (found) exit 0
            if (fallback == "") exit 1
            print fallback
        }
    ' "$2"
}

cleanupGrubUpdate() {
    if [ "$restore" = true ] && ! "$ESCALATION_TOOL" mv -f -- "$backup" /etc/default/grub; then
        printf '%s\n' "Could not restore GRUB settings. Backup kept at $backup." >&2
        backup=
    fi
    "$ESCALATION_TOOL" rm -f -- ${backup:+"$backup"} ${candidate:+"$candidate" "$candidate.new"}
}

updateGrubDefault() (
    backup=
    candidate=
    restore=false
    trap cleanupGrubUpdate 0
    trap 'exit 129' HUP
    trap 'exit 130' INT
    trap 'exit 143' TERM
    candidate=$("$ESCALATION_TOOL" mktemp /boot/grub/grub.cfg.linutil.XXXXXX)
    "$ESCALATION_TOOL" grub-mkconfig -o "$candidate"
    if ! entry=$(findGrubEntry "$1" "$candidate"); then
        printf '%s\n' "Could not find a GRUB entry for $1." >&2
        return 1
    fi
    backup=$("$ESCALATION_TOOL" mktemp /etc/default/grub.linutil.XXXXXX)
    "$ESCALATION_TOOL" cp -p /etc/default/grub "$backup"
    restore=true
    "$ESCALATION_TOOL" sed -i "s|^GRUB_DEFAULT=.*|GRUB_DEFAULT=\"$entry\"|" /etc/default/grub
    "$ESCALATION_TOOL" grub-mkconfig -o "$candidate"
    # The standard header may honor a one-time boot entry from grubenv.
    # Reject any other assignment that could override the requested default.
    # shellcheck disable=SC2016
    if ! "$ESCALATION_TOOL" awk -v entry="$entry" '
        /^### BEGIN .*[/]00_header ###$/ { header = 1 }
        /^### END .*[/]00_header ###$/ { header = 0 }
        /[;{}][[:space:]]*set[[:space:]]+default[[:space:]]*=/ { wrong = 1 }
        /^[[:space:]]*set[[:space:]]+default[[:space:]]*=/ {
            sub(/^[[:space:]]*set[[:space:]]+default[[:space:]]*=[[:space:]]*/, "")
            sub(/[[:space:]]*$/, "")
            if (header && $0 == "\"${next_entry}\"") next
            if ($0 != "\"" entry "\"") wrong = 1
            else found = 1
        }
        END { exit (wrong || !found) }
    ' "$candidate" || [ "$(findGrubEntry "$1" "$candidate")" != "$entry" ]; then
        printf '%s\n' "Could not verify the requested GRUB default." >&2
        return 1
    fi
    # Finish installing the config before handling any further signals.
    trap '' HUP INT TERM
    "$ESCALATION_TOOL" mv -f -- "$candidate" /boot/grub/grub.cfg
    restore=false
)

setDefaultKernel() {
    checkRepo
    if [ -n "$activeRepos" ]; then
        "$ESCALATION_TOOL" pacman -S --needed --noconfirm linux-cachyos-lts linux-cachyos-lts-headers linux-cachyos linux-cachyos-headers

        updateGrubDefault linux-cachyos-lts
    else
        printf "%b\n" "CachyOS repos are not enabled. Install or enable them in /etc/pacman.conf before installing the kernel."
        return 1
    fi
}

checkStockRepo() {
    if ! printf '%s\n' "$repoList" | grep -Fxq "$1"; then
        printf '%s\n' "Enable the stock [$1] repository before migrating CachyOS packages." >&2
        return 1
    fi
    servers=$(pacman-conf --repo "$1" Server)
    usage=$(pacman-conf --repo "$1" Usage)
    if [ -z "$servers" ] || [ "$usage" != All ]; then
        printf '%s\n' "Configure a usable stock [$1] repository with servers and full usage before migrating CachyOS packages." >&2
        return 1
    fi
}

removeRepos() {
    checkRepo
    if [ -n "$activeRepos" ]; then
        if ! printf '%s\n' "$activeRepos" | awk 'seen[$0]++ { duplicate = 1 } END { exit duplicate }'; then
            printf '%s\n' "Resolve duplicate CachyOS repositories before migrating packages." >&2
            return 1
        fi
        checkStockRepo core
        checkStockRepo extra
        installedPackages=$(pacman -Qq)
        if printf '%s\n' "$installedPackages" | grep -q '^lib32-'; then
            checkStockRepo multilib
        fi
        for repo in $activeRepos; do
            if ! awk -v header="[$repo]" '
                {
                    section = $0
                    sub(/#.*/, "", section)
                    sub(/^[[:space:]]+/, "", section)
                    sub(/[[:space:]]+$/, "", section)
                }
                section == header {
                    if (++sections > 1 || $0 != header || getline != 1 ||
                        $0 !~ /^Include = \/etc\/pacman[.]d\/cachyos(-[[:alnum:]-]+)?-mirrorlist$/) {
                        invalid = 1
                        exit
                    }
                    inside = 1
                    next
                }
                /^[[:space:]]*\[/ { inside = 0 }
                inside && $0 !~ /^[[:space:]]*(#.*)?$/ {
                    invalid = 1
                    exit
                }
                END { exit (sections != 1 || invalid) }
            ' /etc/pacman.conf; then
                printf '%s\n' "Remove the $repo repository manually. The CachyOS helper requires a standard repository block in /etc/pacman.conf." >&2
                return 1
            fi
        done
        if ! pacman -Q cachyos-keyring cachyos-mirrorlist cachyos-v3-mirrorlist cachyos-v4-mirrorlist >/dev/null 2>&1; then
            printf '%s\n' "The CachyOS keyring and mirrorlist packages are required by the removal helper. Complete this migration manually." >&2
            return 1
        fi
        printf '%s\n' "Removal can downgrade system packages, replace pacman, and remove the CachyOS keyring and mirrorlists."
        printf '%s\n' "Package hooks may regenerate bootloader files."
        if [ "$#" -eq 0 ]; then
            printf '%s\n' "This option leaves kernel selection to you. Select a maintained replacement if your machine boots a CachyOS kernel."
        fi
        printf '%s' "Continue with CachyOS removal? [y/N] "
        read -r confirm
        case "$confirm" in
            y|Y) ;;
            *) return 1 ;;
        esac
        printf "%b\n" "Removing CachyOS repo.."
        runRepoHelper --remove "$@"
        checkRepo
        if [ -n "$activeRepos" ]; then
            printf "%b\n" "CachyOS repos are still enabled in /etc/pacman.conf."
            return 1
        fi
    else
        if pacman -Q cachyos-keyring >/dev/null 2>&1; then
            printf '%s\n' "CachyOS repos are disabled but the CachyOS keyring is still installed. Check whether package migration needs recovery." >&2
            return 1
        fi
        printf "%b\n" "No CachyOS repos are enabled"
    fi
    if [ "$#" -gt 0 ]; then
        updateGrubDefault linux
    fi
}

main() {
	printf "%b\n" "${YELLOW}Do you want to Install or Uninstall CachyOS${RC}"
    printf "%b\n" "1. ${YELLOW}Install CachyOS repos${RC}"
    printf "%b\n" "2. ${YELLOW}Set CachyOS-LTS default as kernel${RC}"
    printf "%b\n" "3. ${YELLOW}Install CachyOS repos and and set CachyOS-LTS as default kernel${RC}"
    printf "%b\n" "4. ${YELLOW}Remove CachyOS Repos and set default kernel to stock${RC}"
    printf "%b\n" "5. ${YELLOW}Reset default kernel to stock${RC}"
    printf "%b\n" "6. ${YELLOW}Remove CachyOS repos and migrate packages without selecting a kernel${RC}"
    printf "%b" "Enter your choice [1-6]: "
    read -r CHOICE
    if ! command_exists pacman || ! command_exists pacman-conf; then
        printf '%s\n' "CachyOS setup requires pacman and pacman-conf." >&2
        return 1
    fi
    case "$CHOICE" in
        2|3|4|5) checkGrub ;;
    esac
    case "$CHOICE" in
        2|3) preflightGrub ;;
    esac
    # None of these actions needs an AUR helper.
    AUR_HELPER_CHECKED=true checkEnv
    case "$CHOICE" in
        1) setupRepos ;;
        2) setDefaultKernel ;;
        3) setupRepos
           setDefaultKernel ;;
        4) removeRepos --reset-kernel ;;
        5) updateGrubDefault linux ;;
        6) removeRepos ;;
        *) printf "%b\n" "${RED}Invalid choice.${RC}" && exit 1 ;;
    esac
}

main
